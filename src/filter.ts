function escapeRegExp(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function compileAggregatedRegex(keywords: string[]): RegExp {
  const standard: string[] = [];
  const special: string[] = [];

  for (const kw of keywords) {
    const escaped = escapeRegExp(kw);
    const isStandard = /^[a-zA-Z0-9]+$/.test(kw);
    if (isStandard) {
      standard.push(escaped);
    } else {
      special.push(escaped);
    }
  }

  const parts: string[] = [];
  if (standard.length > 0) {
    parts.push(`\\b(?:${standard.join('|')})\\b`);
  }
  if (special.length > 0) {
    const specialPatterns = special.map(sp => `(?:^|[^a-zA-Z0-9])${sp}(?:$|[^a-zA-Z0-9])`);
    parts.push(...specialPatterns);
  }

  if (parts.length === 0) {
    return /$^/;
  }

  return new RegExp(`(?:${parts.join('|')})`, 'i');
}

function compileArabicRegex(keywords: string[]): RegExp {
  const parts = keywords.map(kw => {
    const escaped = escapeRegExp(kw);
    // Matches common Arabic prefixes (ال, و, ب, ل, ف, لل) and suffixes (s, ات, ة, ين, ون, ية)
    return `(?:^|[^\\u0600-\\u06FFa-zA-Z0-9_])(?:ال|و|ب|ل|ف|لل)*${escaped}(?:s|ات|ة|ين|ون|ية)?(?:$|[^\\u0600-\\u06FFa-zA-Z0-9_])`;
  });
  return new RegExp(`(?:${parts.join('|')})`, 'i');
}

const DEFAULT_ENGLISH_REGEX = compileAggregatedRegex(DEFAULT_TECH_KEYWORDS_EN);
const DEFAULT_ARABIC_REGEX = compileArabicRegex(DEFAULT_TECH_KEYWORDS_AR);

let cachedEnvEn = '';
let cachedEnvAr = '';
let compiledEnvRegexEn: RegExp | null = null;
let lowercasedEnvKeywordsAr: string[] = [];

function getEnvFilters() {
  const envEn = process.env.ADDITIONAL_TECH_KEYWORDS_EN || '';
  const envAr = process.env.ADDITIONAL_TECH_KEYWORDS_AR || '';

  if (envEn !== cachedEnvEn) {
    cachedEnvEn = envEn;
    const keywords = envEn.split(',')
      .map(s => s.trim().toLowerCase())
      .filter(Boolean);
    compiledEnvRegexEn = keywords.length > 0 ? compileAggregatedRegex(keywords) : null;
  }

  if (envAr !== cachedEnvAr) {
    cachedEnvAr = envAr;
    lowercasedEnvKeywordsAr = envAr.split(',')
      .map(s => s.trim().toLowerCase())
      .filter(Boolean);
  }

  return {
    envRegexEn: compiledEnvRegexEn,
    envKeywordsAr: lowercasedEnvKeywordsAr
  };
}

export function isTechJob(job: FilterJobInput): boolean {
  // 1. Check if filter is disabled
  if (process.env.ENABLE_TECH_FILTER === 'false') {
    return true;
  }

  // 2. Normalize and check title and category exclusions
  const title = (job.title || '').trim().toLowerCase();
  const category = (job.category || '').trim().toLowerCase();

  if (EXCLUDE_TITLE_CATEGORY_REGEXP.test(title) || EXCLUDE_TITLE_CATEGORY_REGEXP.test(category)) {
    return false;
  }

  // 3. Auto-match Mostaql tech categories (if not excluded)
  if (job.source === 'mostaql' && job.category) {
    const cat = job.category.toLowerCase();
    const isMostaqlTech = 
      cat.includes('برمجة') || 
      cat.includes('تطوير') ||
      cat.includes('ذكاء اصطناعي') ||
      cat.includes('تعلم الآلة') ||
      cat.includes('development') ||
      cat.includes('ai-machine-learning') ||
      cat.includes('artificial intelligence');
    if (isMostaqlTech) {
      return true;
    }
  }

  // 4. Gather text to inspect
  let skillsText = '';
  if (job.skills) {
    if (Array.isArray(job.skills)) {
      skillsText = job.skills.join(' ');
    } else if (typeof job.skills === 'string') {
      try {
        const parsed = JSON.parse(job.skills);
        if (Array.isArray(parsed)) {
          skillsText = parsed.join(' ');
        } else {
          skillsText = job.skills;
        }
      } catch {
        skillsText = job.skills;
      }
    }
  }

  const combinedText = [
    job.title,
    job.description ?? '',
    job.rawText ?? '',
    job.category ?? '',
    skillsText
  ].map(t => t.trim()).filter(Boolean).join('\n');

  const combinedTextLower = combinedText.toLowerCase();

  // Check global exclusions on the combined text
  for (const keyword of EXCLUDE_GLOBAL_KEYWORDS) {
    if (combinedTextLower.includes(keyword)) {
      return false;
    }
  }

  // 5. Test English keywords (Single-pass matching)
  if (DEFAULT_ENGLISH_REGEX.test(combinedText)) {
    return true;
  }

  const { envRegexEn, envKeywordsAr } = getEnvFilters();
  if (envRegexEn && envRegexEn.test(combinedText)) {
    return true;
  }

  // 6. Test Arabic keywords (Morphological Word Boundary matching)
  if (DEFAULT_ARABIC_REGEX.test(combinedText)) {
    return true;
  }

  // Test environment custom Arabic keywords (Substring matching as fallback)
  for (const keyword of envKeywordsAr) {
    if (combinedTextLower.includes(keyword)) {
      return true;
    }
  }

  return false;
}
